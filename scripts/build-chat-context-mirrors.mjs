import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { build } from 'esbuild'

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const checkOnly = process.argv.includes('--check')

const targets = [
  {
    source: 'src/main/chat/context-composer.ts',
    output: 'packages/codesurf-daemon/bin/context-composer.mjs',
  },
  {
    source: 'src/main/chat/prompt-conventions.ts',
    output: 'packages/codesurf-daemon/bin/prompt-conventions.mjs',
  },
]

async function renderTarget(target) {
  const sourcePath = path.join(rootDir, target.source)
  const result = await build({
    entryPoints: [sourcePath],
    bundle: true,
    charset: 'utf8',
    format: 'esm',
    legalComments: 'none',
    platform: 'node',
    target: 'node22',
    treeShaking: false,
    write: false,
  })
  const generated = result.outputFiles[0]?.text
  if (!generated) throw new Error(`esbuild produced no output for ${target.source}`)
  const banner = [
    `// Generated from ${target.source}.`,
    '// Run `npm run build:chat-context-mirrors` to regenerate.',
    '// Do not edit this file directly.',
    '',
  ].join('\n')
  return `${banner}${generated}`
}

const stale = []
for (const target of targets) {
  const outputPath = path.join(rootDir, target.output)
  const expected = await renderTarget(target)
  if (checkOnly) {
    const actual = await readFile(outputPath, 'utf8').catch(() => '')
    if (actual !== expected) stale.push(target.output)
  } else {
    await writeFile(outputPath, expected)
  }
}

if (stale.length > 0) {
  throw new Error(
    `Generated chat context mirrors are stale:\n${stale.map(file => `- ${file}`).join('\n')}\n` +
      'Run `npm run build:chat-context-mirrors`.',
  )
}
